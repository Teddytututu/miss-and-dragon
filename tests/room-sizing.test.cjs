const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync('board/discussion.js','utf8'),context);
const s=context.window.DiscussionRoom.sizing;
assert.equal(s.clampScale('corrupt'),1);
assert.equal(s.clampScale(null),1);
assert.equal(s.clampScale(0),.8);
assert.equal(s.clampScale(2),1.6);
assert.equal(s.clampScale(1.2000000000000002),1.2);
assert.equal(s.zoomKey({key:'=',ctrlKey:true}),1);
assert.equal(s.zoomKey({key:'+',metaKey:true}),1);
assert.equal(s.zoomKey({key:'-',ctrlKey:true}),-1);
assert.equal(s.zoomKey({key:'0',metaKey:true}),0);
assert.equal(s.zoomKey({key:'+',ctrlKey:false}),null);
assert.equal(s.zoomKey({key:'=',ctrlKey:true,isComposing:true}),null);
assert.equal(s.nearestStop(360,800),.45);
assert.equal(s.nearestStop(590,800),.75);
assert.equal(s.nearestStop(790,800),1);
assert.equal(s.nearestStop(-80,800),.45);
assert.equal(s.dismissDrawer(.45,81),true);
assert.equal(s.dismissDrawer(.45,80),false);
assert.equal(s.dismissDrawer(.75,250),false);
console.log('18 sizing assertions passed');
